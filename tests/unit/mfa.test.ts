test("RFC 6238 SHA1 reference vectors are generated by the standards library", () => {
  const secret = Buffer.from("12345678901234567890");
  for (const [seconds, expected] of [
    [59, "94287082"],
    [1111111109, "07081804"],
    [1111111111, "14050471"],
    [1234567890, "89005924"],
    [2000000000, "69279037"],
    [20000000000, "65353130"],
  ] as const)
    assert.equal(otp(secret, seconds * 1000, 8), expected);
});
test("TOTP accepts only ±1 step and rejects already accepted/older counters", () => {
  const secret = Buffer.alloc(32, 42),
    now = new Date("2026-10-30T10:00:00Z"),
    step = BigInt(Math.floor(now.getTime() / 30000));
  assert.equal(
    acceptedStep(secret, otp(secret, now.getTime()), now, null),
    step,
  );
  assert.equal(
    acceptedStep(secret, otp(secret, now.getTime() - 30000), now, null),
    step - 1n,
  );
  assert.equal(
    acceptedStep(secret, otp(secret, now.getTime() + 30000), now, null),
    step + 1n,
  );
  assert.equal(
    acceptedStep(secret, otp(secret, now.getTime() + 60000), now, null),
    null,
  );
  assert.equal(
    acceptedStep(secret, otp(secret, now.getTime()), now, step),
    null,
  );
  assert.equal(acceptedStep(secret, "123", now, null), null);
});
test("AES-GCM binds user, generation, enrollment and tag; keyring loss fails closed", () => {
  const key = randomBytes(32),
    ring = { active: "one", keys: new Map([["one", key]]) },
    owner = { id: randomUUID(), user_id: randomUUID(), generation: 1 },
    secret = randomBytes(32),
    envelope = { ...owner, ...sealSecret(secret, owner, ring) };
  assert.deepEqual(openSecret(envelope, ring), secret);
  for (const changed of [
    { ...envelope, user_id: randomUUID() },
    { ...envelope, id: randomUUID() },
    { ...envelope, generation: 2 },
    { ...envelope, tag: randomBytes(16) },
  ])
    assert.throws(() => openSecret(changed, ring));
  assert.throws(() =>
    openSecret(envelope, {
      active: "two",
      keys: new Map([["two", randomBytes(32)]]),
    }),
  );
  assert.throws(() =>
    mfaKeyring({ MFA_ACTIVE_KEY_ID: "missing", MFA_ENCRYPTION_KEYS: "{}" }),
  );
});
test("local key initialization preserves existing keys and rejects partial/invalid configuration", async () => {
  await mkdir(".local", { recursive: true });
  const file = ".local/test-keyring-" + randomUUID() + ".env";
  await writeFile(file, "EXISTING=preserved\n");
  try {
    assert.equal(await initializeKeyringFile(file), true);
    const once = await readFile(file, "utf8");
    assert.equal(await initializeKeyringFile(file), false);
    assert.equal(await readFile(file, "utf8"), once);
    await writeFile(file, "MFA_ACTIVE_KEY_ID=lost\n");
    await assert.rejects(() => initializeKeyringFile(file));
    assert.equal(await readFile(file, "utf8"), "MFA_ACTIVE_KEY_ID=lost\n");
  } finally {
    await unlink(file);
  }
});
test("DUTY policy is separate: idle 30 minutes, absolute valid_until bounded by 12 hours; ACCOUNT stays 15/60", () => {
  const p = securitySchema.parse({}),
    now = new Date("2026-10-30T00:00:00Z");
  assert.equal(p.idleMinutes, 15);
  assert.equal(p.absoluteMinutes, 60);
  assert.equal(p.pinEnabled, false);
  const long = dutySessionExpiry(now, new Date("2026-11-01T00:00:00Z"), p);
  assert.equal(long.idle.toISOString(), "2026-10-30T00:30:00.000Z");
  assert.equal(long.absolute.toISOString(), "2026-10-30T12:00:00.000Z");
  assert.equal(
    dutySessionExpiry(
      now,
      new Date("2026-10-30T08:00:00Z"),
      p,
    ).absolute.toISOString(),
    "2026-10-30T08:00:00.000Z",
  );
  assert.throws(() => securitySchema.parse({ dutyMaxHours: 13 }));
  assert.throws(() => dutySessionExpiry(now, now, p));
});
test("operator guard refuses production/remote/unrecognized databases without explicit flag and always refuses app credentials", () => {
  const url =
    "postgresql://libetario_migrator:placeholder@127.0.0.1:55432/libetario_test";
  assert.throws(() => assertOperatorTarget(url, false, "production"));
  assert.doesNotThrow(() => assertOperatorTarget(url, true, "production"));
  assert.throws(() =>
    assertOperatorTarget(
      url.replace("127.0.0.1", "example.invalid"),
      false,
      "development",
    ),
  );
  assert.throws(() =>
    assertOperatorTarget(
      url.replace("/libetario_test", "/unrelated"),
      false,
      "development",
    ),
  );
  assert.throws(() =>
    assertOperatorTarget(
      url.replace("libetario_migrator", "libetario_runtime"),
      true,
      "production",
    ),
  );
});
